/**
 * 慈善活动内容工场 · 报告 PDF 与海报的 HTML（纯函数，可单测）。
 *
 * PDF 走离屏 Chromium printToPDF：阿语版整页 dir="rtl"、lang="ar"，字体栈优先系统阿语字体，
 * Chromium 会把实际用到的字形子集嵌进 PDF（阿语字体嵌入由此保证）。
 * 海报 1080×1920（9:16），素材照片做背景 + 渐变压暗 + 标题 + 机构名。
 */
import type { CharityArchive, CharityLang, CharityReportContent } from '@totalclaw/ipc-contracts';

export const POSTER_W = 1080;
export const POSTER_H = 1920;

export function esc(s: unknown): string {
  return String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export function fontStack(lang: CharityLang): string {
  if (lang === 'ar') return '"Noto Naskh Arabic","Noto Sans Arabic","Geeza Pro","Baghdad","Al Bayan","Arial Unicode MS","Tahoma","Segoe UI",sans-serif';
  if (lang === 'zh') return '"PingFang SC","Hiragino Sans GB","Microsoft YaHei","Noto Sans CJK SC","Source Han Sans SC","Arial Unicode MS",sans-serif';
  return '"Inter","Helvetica Neue","Segoe UI",Arial,"PingFang SC",sans-serif';
}

export function dirOf(lang: CharityLang): 'rtl' | 'ltr' { return lang === 'ar' ? 'rtl' : 'ltr'; }

const L: Record<CharityLang, Record<string, string>> = {
  zh: { report: '活动报告', date: '活动日期', loc: '活动地点', n: '参与人数', money: '善款金额', host: '主办方', overview: '活动概况', highlights: '活动亮点', scene: '现场回顾', thanks: '致谢', none: '未披露', people: '人', footer: '本报告由 TotalClaw 慈善活动内容工场生成', gallery: '现场影像' },
  en: { report: 'Event Report', date: 'Date', loc: 'Location', n: 'Participants', money: 'Funds Raised', host: 'Organizer', overview: 'Overview', highlights: 'Highlights', scene: 'On Site', thanks: 'Acknowledgements', none: 'Not disclosed', people: '', footer: 'Generated by TotalClaw Charity Content Studio', gallery: 'Gallery' },
  ar: { report: 'تقرير الفعالية', date: 'التاريخ', loc: 'المكان', n: 'المشاركون', money: 'التبرعات', host: 'الجهة المنظمة', overview: 'نظرة عامة', highlights: 'أبرز اللحظات', scene: 'من الموقع', thanks: 'شكر وتقدير', none: 'غير معلن', people: '', footer: 'أُنشئ بواسطة استوديو المحتوى الخيري TotalClaw', gallery: 'من الفعالية' },
};

export function labels(lang: CharityLang): Record<string, string> { return L[lang]; }

export function formatParticipants(a: CharityArchive, lang: CharityLang): string {
  if (a.participants == null) return L[lang].none;
  return lang === 'zh' ? `${a.participants} 人` : String(a.participants);
}

export interface ReportHtmlOptions {
  /** 现场照片 data URL（最多 3 张，进封面拼图） */
  photos?: string[];
  /** 阿语 PDF 首页截图用：加一段验收水印说明（默认不加） */
  brand?: string;
}

export function buildReportHtml(lang: CharityLang, a: CharityArchive, c: CharityReportContent, opts: ReportHtmlOptions = {}): string {
  const t = L[lang];
  const photos = (opts.photos || []).slice(0, 3);
  const dir = dirOf(lang);
  const facts: Array<[string, string]> = [
    [t.date, a.date || t.none],
    [t.loc, a.location[lang] || t.none],
    [t.n, formatParticipants(a, lang)],
    [t.money, a.donation || t.none],
    [t.host, a.organizer[lang] || a.orgName[lang]],
  ];
  return `<!doctype html><html lang="${lang === 'zh' ? 'zh-CN' : lang}" dir="${dir}"><head><meta charset="utf-8">
<title>${esc(c.title)}</title>
<style>
  @page { size: A4; margin: 14mm 14mm 16mm; }
  * { box-sizing: border-box; }
  html, body { margin: 0; padding: 0; }
  body { font-family: ${fontStack(lang)}; color: #16203a; font-size: 12.5pt; line-height: 1.75; direction: ${dir}; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
  .cover { background: linear-gradient(135deg, #123c5a 0%, #1e6f5c 100%); color: #fff; border-radius: 14px; padding: 26px 28px; margin-bottom: 18px; }
  .eyebrow { font-size: 10.5pt; letter-spacing: .08em; opacity: .85; text-transform: uppercase; }
  h1 { font-size: 24pt; line-height: 1.3; margin: 8px 0 6px; font-weight: 800; }
  .org { font-size: 13pt; opacity: .95; }
  .gallery { display: grid; grid-template-columns: repeat(${Math.max(1, photos.length)}, 1fr); gap: 8px; margin: 14px 0 0; }
  .gallery img { width: 100%; height: 150px; object-fit: cover; border-radius: 10px; display: block; }
  .facts { display: grid; grid-template-columns: repeat(5, 1fr); gap: 8px; margin: 0 0 18px; }
  .fact { border: 1px solid #dfe5ef; border-radius: 10px; padding: 8px 10px; background: #f7f9fc; }
  .fact small { display: block; color: #64748b; font-size: 9pt; }
  .fact strong { display: block; font-size: 12pt; color: #0f2b46; word-break: break-word; }
  h2 { font-size: 14.5pt; color: #1e6f5c; margin: 16px 0 6px; padding-${dir === 'rtl' ? 'right' : 'left'}: 10px; border-${dir === 'rtl' ? 'right' : 'left'}: 4px solid #1e6f5c; }
  p { margin: 0 0 8px; text-align: ${dir === 'rtl' ? 'right' : 'justify'}; }
  ul { margin: 0; padding-${dir === 'rtl' ? 'right' : 'left'}: 20px; }
  li { margin: 0 0 4px; }
  .thanks { background: #f0faf5; border-radius: 10px; padding: 10px 14px; }
  .footer { margin-top: 22px; font-size: 9pt; color: #94a3b8; border-top: 1px solid #e5e9f0; padding-top: 8px; display: flex; justify-content: space-between; }
</style></head><body>
<section class="cover">
  <div class="eyebrow">${esc(t.report)}</div>
  <h1>${esc(c.title)}</h1>
  <div class="org">${esc(a.orgName[lang])}${a.date ? ` · ${esc(a.date)}` : ''}</div>
  ${photos.length ? `<div class="gallery">${photos.map((p) => `<img src="${p}" alt="">`).join('')}</div>` : ''}
</section>
<section class="facts">${facts.map(([k, v]) => `<div class="fact"><small>${esc(k)}</small><strong>${esc(v)}</strong></div>`).join('')}</section>
<h2>${esc(t.overview)}</h2><p>${esc(c.overview)}</p>
<h2>${esc(t.highlights)}</h2><ul>${c.highlights.map((h) => `<li>${esc(h)}</li>`).join('')}</ul>
<h2>${esc(t.scene)}</h2><p>${esc(c.scene)}</p>
<h2>${esc(t.thanks)}</h2><p class="thanks">${esc(c.thanks)}</p>
<div class="footer"><span>${esc(a.orgName[lang])}</span><span>${esc(opts.brand || t.footer)}</span></div>
</body></html>`;
}

export interface PosterHtmlOptions {
  /** 背景照片 data URL；没有就用品牌渐变 */
  background?: string;
}

/** 9:16 海报：背景照片 + 双层渐变 + 标题/机构/日期地点/一句话 */
export function buildPosterHtml(lang: CharityLang, a: CharityArchive, c: CharityReportContent, opts: PosterHtmlOptions = {}): string {
  const t = L[lang];
  const dir = dirOf(lang);
  const tagline = c.captions[0] && c.captions[0] !== a.eventName[lang] ? c.captions[0] : (a.summary[lang] || '');
  const meta = [a.date, a.location[lang]].filter(Boolean).join(' · ');
  const bg = opts.background
    ? `url("${opts.background}") center/cover no-repeat`
    : 'linear-gradient(160deg,#123c5a,#1e6f5c 60%,#0b2a3f)';
  return `<!doctype html><html lang="${lang === 'zh' ? 'zh-CN' : lang}" dir="${dir}"><head><meta charset="utf-8"><style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  html, body { width: ${POSTER_W}px; height: ${POSTER_H}px; overflow: hidden; background: #0b2a3f; }
  body { font-family: ${fontStack(lang)}; color: #fff; direction: ${dir}; }
  .bg { position: absolute; inset: -12px; background: ${bg}; filter: ${opts.background ? 'blur(2px) brightness(.72) saturate(1.1)' : 'none'}; }
  .shade { position: absolute; inset: 0; background: linear-gradient(180deg, rgba(8,24,40,.45) 0%, rgba(8,24,40,.05) 35%, rgba(8,24,40,.55) 62%, rgba(8,24,40,.94) 100%); }
  .top { position: absolute; top: 72px; ${dir === 'rtl' ? 'right' : 'left'}: 72px; ${dir === 'rtl' ? 'left' : 'right'}: 72px; display: flex; align-items: center; gap: 18px; }
  .badge { width: 64px; height: 64px; border-radius: 18px; background: rgba(255,255,255,.16); border: 2px solid rgba(255,255,255,.55); display: flex; align-items: center; justify-content: center; font-size: 30px; }
  .org { font-size: 34px; font-weight: 700; text-shadow: 0 2px 12px rgba(0,0,0,.45); line-height: 1.25; }
  .bottom { position: absolute; ${dir === 'rtl' ? 'right' : 'left'}: 72px; ${dir === 'rtl' ? 'left' : 'right'}: 72px; bottom: 120px; }
  .kicker { display: inline-block; font-size: 26px; letter-spacing: .06em; background: #2bb673; padding: 8px 22px; border-radius: 999px; margin-bottom: 26px; font-weight: 700; }
  h1 { font-size: ${lang === 'ar' ? 96 : 92}px; line-height: 1.12; font-weight: 900; text-shadow: 0 4px 24px rgba(0,0,0,.55); margin-bottom: 28px; word-break: break-word; }
  .tag { font-size: 38px; line-height: 1.45; color: rgba(255,255,255,.94); margin-bottom: 30px; }
  .meta { font-size: 30px; color: rgba(255,255,255,.85); display: flex; gap: 14px; align-items: center; }
  .meta i { width: 10px; height: 10px; border-radius: 50%; background: #2bb673; display: inline-block; }
  .foot { position: absolute; bottom: 48px; ${dir === 'rtl' ? 'right' : 'left'}: 72px; ${dir === 'rtl' ? 'left' : 'right'}: 72px; display: flex; justify-content: space-between; font-size: 22px; color: rgba(255,255,255,.6); }
</style></head><body>
<div class="bg"></div><div class="shade"></div>
<div class="top"><div class="badge">✦</div><div class="org">${esc(a.orgName[lang])}</div></div>
<div class="bottom">
  <div class="kicker">${esc(t.report === 'Event Report' ? 'CHARITY EVENT' : lang === 'ar' ? 'فعالية خيرية' : '公益活动')}</div>
  <h1>${esc(a.eventName[lang])}</h1>
  ${tagline ? `<div class="tag">${esc(tagline)}</div>` : ''}
  ${meta ? `<div class="meta"><i></i><span>${esc(meta)}</span></div>` : ''}
</div>
<div class="foot"><span>${esc(a.organizer[lang] || a.orgName[lang])}</span><span>${esc(a.donation ? `${t.money}: ${a.donation}` : '')}</span></div>
</body></html>`;
}
