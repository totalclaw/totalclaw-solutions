export type MmMobileText = typeof MM_MOBILE_TEXT;

/** 服务端（拼 401 页面等）取文案；与页面脚本里的 tx 同一套规则 */
export function mmText(path: string, vars?: Record<string, string | number>): string {
  let v: unknown = MM_MOBILE_TEXT;
  for (const k of path.split('.')) v = v && typeof v === 'object' ? (v as Record<string, unknown>)[k] : undefined;
  if (typeof v !== 'string') return path;
  return vars ? v.replace(/\{(\w+)\}/g, (_m, k: string) => (vars[k] == null ? '' : String(vars[k]))) : v;
}
