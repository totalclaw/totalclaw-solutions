/** 小标题形态：去掉序号后 ≤20 字且没有句内标点 —— 用来把正文条目和小标题分开 */
export function isHeadingShape(body: string): boolean {
  return body.length > 0 && body.length <= 20 && !/[，,。；;]/.test(body);
}

/** 一眼就是正文而不是标题 */
export function looksLikeBody(line: string): boolean {
  if (line.length > 48) return true;
  if (/[。；;!?]$/.test(line)) return true;
  return (line.match(/[，,。；;：:、]/g) || []).length >= 3;
}

