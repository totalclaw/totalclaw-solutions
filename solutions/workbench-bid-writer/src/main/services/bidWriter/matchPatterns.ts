/** 一眼是首页 / 栏目页而不是公告详情页（没有 id 段、路径太浅） */
export function looksLikeListingUrl(url: string): boolean {
  try {
    const u = new URL(url);
    const path = u.pathname.replace(/\/+$/, '');
    if (!path || path === '/' || path.length < 8) return true;
    const last = path.split('/').pop() || '';
    // 详情页一般带数字 id 或长 hash；`/list`、`/index`、`/column` 这种是栏目页
    if (/^(index|list|column|channel|search|home)(\.\w+)?$/i.test(last)) return true;
    return !/\d{4,}|[0-9a-f]{12,}/i.test(path + u.search);
  } catch {
    return true;
  }
}

